import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { geoArea } from "d3-geo";
import { feature } from "topojson-client";
import { topology } from "topojson-server";
import {
  presimplify,
  quantile,
  simplify,
  sphericalTriangleArea,
} from "topojson-simplify";

const SOURCE_URL =
  "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/ca96624a56bd078437bca8184e78163e5039ad19/geojson/ne_110m_land.geojson";
const OUTPUT_URL = new URL(
  "../src/components/chart/globe-land.ts",
  import.meta.url,
);
const QUANTIZATION = 100_000;
const SIMPLIFICATION_QUANTILE = 0.5;
const COORDINATE_PRECISION = 2;
const COORDINATE_SCALE = 10 ** COORDINATE_PRECISION;

function normalizePolygon(polygon) {
  const polygonObject = { type: "Polygon", coordinates: polygon };
  if (geoArea(polygonObject) <= 2 * Math.PI) return polygon;
  return polygon.map((ring) => [...ring].reverse());
}

function roundGeometry(geometry) {
  const roundRing = (ring) => {
    const points = ring
      .map(([longitude, latitude]) => [
        Number(longitude.toFixed(COORDINATE_PRECISION)),
        Number(latitude.toFixed(COORDINATE_PRECISION)),
      ])
      .filter(
        (point, index, allPoints) =>
          index === 0 ||
          point[0] !== allPoints[index - 1][0] ||
          point[1] !== allPoints[index - 1][1],
      );
    if (
      points[0][0] !== points.at(-1)[0] ||
      points[0][1] !== points.at(-1)[1]
    ) {
      points.push([...points[0]]);
    }
    return new Set(points.slice(0, -1).map((point) => point.join(","))).size >=
      3
      ? points
      : null;
  };

  return {
    ...geometry,
    coordinates: geometry.coordinates.flatMap((polygon) => {
      const [outerRing, ...holes] = polygon.map(roundRing);
      return outerRing
        ? [[outerRing, ...holes.filter((ring) => ring !== null)]]
        : [];
    }),
  };
}

function encodeGeometry(geometry) {
  return geometry.coordinates.map((polygon) =>
    polygon.map((ring) => {
      let previousLongitude = 0;
      let previousLatitude = 0;
      return ring.map(([longitude, latitude], index) => {
        const scaledLongitude = Math.round(longitude * COORDINATE_SCALE);
        const scaledLatitude = Math.round(latitude * COORDINATE_SCALE);
        const point =
          index === 0
            ? [scaledLongitude, scaledLatitude]
            : [
                scaledLongitude - previousLongitude,
                scaledLatitude - previousLatitude,
              ];
        previousLongitude = scaledLongitude;
        previousLatitude = scaledLatitude;
        return point;
      });
    }),
  );
}

function formatCoordinates(coordinates) {
  const polygons = coordinates
    .map(
      (polygon) => `  [
${polygon
  .map(
    (ring) => `    [
${ring
  .map(([longitude, latitude]) => `      [${longitude}, ${latitude}],`)
  .join("\n")}
    ],`,
  )
  .join("\n")}
  ],`,
    )
    .join("\n");
  return `[
${polygons}
]`;
}

function countPoints(geometry) {
  return geometry.coordinates.reduce(
    (total, polygon) =>
      total +
      polygon.reduce((polygonTotal, ring) => polygonTotal + ring.length, 0),
    0,
  );
}

const response = await fetch(SOURCE_URL);
if (!response.ok) {
  throw new Error(`Natural Earth download failed: ${response.status}`);
}

const geoJson = await response.json();
const coordinates = geoJson.features.flatMap(({ geometry }) =>
  geometry.type === "Polygon"
    ? [normalizePolygon(geometry.coordinates)]
    : geometry.coordinates.map(normalizePolygon),
);
const land = { type: "MultiPolygon", coordinates };
const presimplified = presimplify(
  topology({ land }, QUANTIZATION),
  sphericalTriangleArea,
);
const threshold = quantile(presimplified, SIMPLIFICATION_QUANTILE);
const simplified = simplify(presimplified, threshold);
const rounded = roundGeometry(
  feature(simplified, simplified.objects.land).geometry,
);
// Simplifying can flip a small ring's winding; fix it again.
const geometry = {
  ...rounded,
  coordinates: rounded.coordinates.map(normalizePolygon),
};
const encodedCoordinates = encodeGeometry(geometry);
const source = `/**
 * Simplified Natural Earth 1:110m land geometry.
 * Natural Earth data is public domain: https://www.naturalearthdata.com/about/terms-of-use/
 * Source: ${SOURCE_URL}
 * Generated by: packages/kumo/scripts/generate-globe-land.mjs
 */
import type { GeoPermissibleObjects } from "d3-geo";

const COORDINATE_SCALE = ${COORDINATE_SCALE};
const ENCODED_LAND_COORDINATES = ${formatCoordinates(encodedCoordinates)};

function decodeLand(encoded: number[][][][]): GeoPermissibleObjects {
  return {
    type: "MultiPolygon",
    coordinates: encoded.map((polygon) =>
      polygon.map((ring) => {
        let longitude = 0;
        let latitude = 0;
        return ring.map(([longitudeDelta, latitudeDelta], index) => {
          longitude = index === 0 ? longitudeDelta : longitude + longitudeDelta;
          latitude = index === 0 ? latitudeDelta : latitude + latitudeDelta;
          return [longitude / COORDINATE_SCALE, latitude / COORDINATE_SCALE];
        });
      }),
    ),
  } as GeoPermissibleObjects;
}

// Pure so bundles that only use the flat maps drop the land data.
export const GLOBE_LAND = /* @__PURE__ */ decodeLand(ENCODED_LAND_COORDINATES);
`;

await writeFile(OUTPUT_URL, source);
console.log(
  `Generated ${fileURLToPath(OUTPUT_URL)} (${countPoints(geometry)} points, ${Buffer.byteLength(source)} bytes)`,
);
